// Builds supabase/seed-blog.sql from the Markdown articles in supabase/blog/.
// Usage: node scripts/build-blog-seed.mjs
// Each article starts with a small header (title, slug, category, tags, excerpt, seo_description, days_ago).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'supabase', 'blog')
const q = (s) => `'${String(s).replace(/'/g, "''")}'`

function parse(file) {
  const raw = readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n')
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/)
  if (!m) throw new Error(`${file}: missing header`)
  const meta = {}
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':')
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim()
  }
  return { meta, body: m[2].trim() }
}

const problems = []
const rows = readdirSync(dir).filter((f) => f.endsWith('.md')).sort().map((f) => {
  const { meta, body } = parse(f)
  const words = body.split(/\s+/).length
  if (meta.title.length > 65) problems.push(`${f}: title is ${meta.title.length} characters (aim for 65 or fewer)`)
  if (meta.seo_description.length > 160) problems.push(`${f}: SEO description is ${meta.seo_description.length} characters (aim for 160 or fewer)`)
  if (meta.seo_description.length < 100) problems.push(`${f}: SEO description is short (${meta.seo_description.length})`)
  if (meta.excerpt.length > 400) problems.push(`${f}: excerpt is too long`)
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(meta.slug)) problems.push(`${f}: invalid slug`)
  if (body.includes('$md$')) problems.push(`${f}: contains the quoting marker`)
  if (/—/.test(body)) problems.push(`${f}: contains an em dash`)
  console.log(`${meta.slug}: ${words} words, title ${meta.title.length}, description ${meta.seo_description.length}`)
  const tags = meta.tags.split(',').map((t) => t.trim()).filter(Boolean)
  return `(${q(meta.title)}, ${q(meta.slug)}, ${q(meta.excerpt)}, $md$${body}$md$, ${q(`/img/blog/${meta.slug}.jpg`)}, ${q(meta.category)}, array[${tags.map(q).join(', ')}], ${q(meta.seo_description)}, 'Digital Legends Team', 'published', now() - interval '${Number(meta.days_ago)} days')`
})

if (problems.length) { console.error('\nFix these first:\n- ' + problems.join('\n- ')); process.exit(1) }

const sql = `-- Six launch articles for the blog. Generated by scripts/build-blog-seed.mjs from supabase/blog/*.md.
-- Run once in the Supabase SQL Editor (after supabase/schema.sql). Running it again refreshes the text of these six posts.
-- Cover images are served from the website itself (/img/blog/...), so no upload is needed.

insert into public.blog_posts (title, slug, excerpt, content, cover_image, category, tags, seo_description, author_name, status, published_at)
values
${rows.join(',\n')}
on conflict (slug) do update set
  title = excluded.title,
  excerpt = excluded.excerpt,
  content = excluded.content,
  cover_image = excluded.cover_image,
  category = excluded.category,
  tags = excluded.tags,
  seo_description = excluded.seo_description;
`
writeFileSync(join(root, 'supabase', 'seed-blog.sql'), sql)
console.log(`\nWrote supabase/seed-blog.sql (${rows.length} posts)`)
